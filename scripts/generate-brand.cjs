/**
 * Generates Frame & Flow brand assets from the Geist SemiBold typeface.
 *
 * Text is converted to outlined SVG paths so the logo renders identically
 * everywhere, with no font dependency.
 *
 * Usage (one-off; these packages are intentionally not project dependencies):
 *   npm i --no-save opentype.js@1.3.4 geist@1.9.2
 *   node scripts/generate-brand.cjs
 *
 * PNG/ICO output uses the Playwright + Chromium install available in the
 * environment (require('playwright')). Skip with --svg-only.
 *
 * Outputs:
 *   src/components/layout/brand-glyphs.ts   path data for the <Logo> component
 *   public/brand/frame-and-flow-wordmark.svg        (default, light backgrounds)
 *   public/brand/frame-and-flow-wordmark-light.svg  (for light backgrounds)
 *   public/brand/frame-and-flow-wordmark-dark.svg   (for dark backgrounds)
 *   public/brand/frame-and-flow-monogram.svg        f&f. monogram tile
 *   public/icon.svg                                 SVG favicon
 *   public/favicon.ico, public/apple-touch-icon.png, public/brand/icon-192.png, icon-512.png
 *   public/og.png                                   1200×630 social sharing image
 */
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");

const root = path.resolve(__dirname, "..");
// The `geist` package ships TTF files (opentype.js cannot read WOFF2).
const geistDist = path.dirname(require.resolve("geist/font")); // resolves only, does not execute
const font = opentype.loadSync(path.join(geistDist, "fonts/geist-sans/Geist-SemiBold.ttf"));

const COLORS = {
  charcoal: "#20231F",
  ivory: "#F7F7F2",
  sage: "#526B50",
  sageLight: "#B4C9AE",
};

function build(segments, { size = 100, tracking }) {
  const scale = size / font.unitsPerEm;
  let x = 0;
  let prev = null;
  const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  const raw = segments.map((seg) => {
    const glyphPaths = [];
    for (const ch of seg.text) {
      const g = font.charToGlyph(ch);
      if (prev) x += font.getKerningValue(prev, g) * scale;
      const p = g.getPath(x, 0, size);
      const bb = p.getBoundingBox();
      box.minX = Math.min(box.minX, bb.x1);
      box.maxX = Math.max(box.maxX, bb.x2);
      box.minY = Math.min(box.minY, bb.y1);
      box.maxY = Math.max(box.maxY, bb.y2);
      glyphPaths.push(p);
      x += g.advanceWidth * scale + tracking * size;
      prev = g;
    }
    return { role: seg.role, glyphPaths };
  });
  // Re-render with the bounding box moved to the origin.
  const dx = -box.minX;
  const dy = -box.minY;
  const parts = raw.map(({ role, glyphPaths }) => ({
    role,
    d: glyphPaths
      .map((p) => {
        p.commands.forEach((c) => {
          for (const k of ["x", "x1", "x2"]) if (k in c) c[k] += dx;
          for (const k of ["y", "y1", "y2"]) if (k in c) c[k] += dy;
        });
        return p.toPathData(2);
      })
      .join(""),
  }));
  return {
    width: +(box.maxX - box.minX).toFixed(2),
    height: +(box.maxY - box.minY).toFixed(2),
    parts,
  };
}

const wordmark = build(
  [
    { text: "frame", role: "ink" },
    { text: "&", role: "accent" },
    { text: "flow", role: "ink" },
    { text: ".", role: "accent" },
  ],
  { tracking: -0.045 },
);
const monogram = build(
  [
    { text: "f", role: "ink" },
    { text: "&", role: "accent" },
    { text: "f", role: "ink" },
    { text: ".", role: "accent" },
  ],
  { tracking: -0.06 },
);

/* ---------- React path data ---------- */
const ts = `// Generated by scripts/generate-brand.cjs — do not edit by hand.
export type BrandGlyphs = {
  width: number;
  height: number;
  parts: { role: "ink" | "accent"; d: string }[];
};

export const wordmarkGlyphs: BrandGlyphs = ${JSON.stringify(wordmark)};

export const monogramGlyphs: BrandGlyphs = ${JSON.stringify(monogram)};
`;
fs.writeFileSync(path.join(root, "src/components/layout/brand-glyphs.ts"), ts);

/* ---------- SVG files ---------- */
function wordmarkSvg({ ink, accent, title }) {
  const pad = 8;
  const w = +(wordmark.width + pad * 2).toFixed(2);
  const h = +(wordmark.height + pad * 2).toFixed(2);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-labelledby="t">
  <title id="t">${title}</title>
  <g transform="translate(${pad} ${pad})">
${wordmark.parts.map((p) => `    <path fill="${p.role === "ink" ? ink : accent}" d="${p.d}"/>`).join("\n")}
  </g>
</svg>
`;
}

function monogramTile({ size = 64, radius = 14, bg = COLORS.charcoal, ink = COLORS.ivory, accent = COLORS.sageLight, fill = 0.74 }) {
  const scale = (size * fill) / monogram.width;
  const w = monogram.width * scale;
  const h = monogram.height * scale;
  const x = (size - w) / 2;
  // Optically centre on the x-height rather than the ascender.
  const y = (size - h) / 2 + h * 0.04;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  <rect width="${size}" height="${size}" rx="${radius}" fill="${bg}"/>
  <g transform="translate(${x.toFixed(2)} ${y.toFixed(2)}) scale(${scale.toFixed(4)})">
${monogram.parts.map((p) => `    <path fill="${p.role === "ink" ? ink : accent}" d="${p.d}"/>`).join("\n")}
  </g>
</svg>
`;
}

const light = wordmarkSvg({ ink: COLORS.charcoal, accent: COLORS.sage, title: "Frame &amp; Flow Studio" });
const dark = wordmarkSvg({ ink: COLORS.ivory, accent: COLORS.sageLight, title: "Frame &amp; Flow Studio" });
fs.writeFileSync(path.join(root, "public/brand/frame-and-flow-wordmark.svg"), light);
fs.writeFileSync(path.join(root, "public/brand/frame-and-flow-wordmark-light.svg"), light);
fs.writeFileSync(path.join(root, "public/brand/frame-and-flow-wordmark-dark.svg"), dark);
const tile = monogramTile({});
fs.writeFileSync(path.join(root, "public/brand/frame-and-flow-monogram.svg"), tile);
fs.writeFileSync(path.join(root, "public/icon.svg"), tile);
console.log("SVG assets written.");

if (process.argv.includes("--svg-only")) process.exit(0);

/* ---------- Raster icons ---------- */
(async () => {
  const { chromium } = require("playwright");
  const browser = await chromium.launch();
  const page = await browser.newPage();
  async function png(svg, size) {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(
      `<html><body style="margin:0;background:transparent">${svg.replace(/width="\d+" height="\d+"/, `width="${size}" height="${size}"`)}</body></html>`,
    );
    return page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
  }
  // Full-bleed (no rounded corners) for platforms that apply their own mask.
  const square = monogramTile({ radius: 0, fill: 0.64 });
  fs.writeFileSync(path.join(root, "public/apple-touch-icon.png"), await png(square, 180));
  fs.writeFileSync(path.join(root, "public/brand/icon-192.png"), await png(square, 192));
  fs.writeFileSync(path.join(root, "public/brand/icon-512.png"), await png(square, 512));

  // favicon.ico with embedded PNGs (16, 32, 48).
  const sizes = [16, 32, 48];
  const images = [];
  for (const s of sizes) images.push(await png(monogramTile({ radius: s * 0.2, fill: 0.8 }), s));
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map((img, i) => {
    const e = Buffer.alloc(16);
    e.writeUInt8(sizes[i], 0);
    e.writeUInt8(sizes[i], 1);
    e.writeUInt8(0, 2);
    e.writeUInt8(0, 3);
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(32, 6);
    e.writeUInt32LE(img.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += img.length;
    return e;
  });
  fs.writeFileSync(path.join(root, "public/favicon.ico"), Buffer.concat([header, ...entries, ...images]));

  // Social sharing image (1200×630).
  const geist = fs.readFileSync(path.join(root, "node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2")).toString("base64");
  const wm = `<svg width="${((wordmark.width / wordmark.height) * 44).toFixed(1)}" height="44" viewBox="0 0 ${wordmark.width} ${wordmark.height}">${wordmark.parts
    .map((p) => `<path fill="${p.role === "ink" ? COLORS.charcoal : COLORS.sage}" d="${p.d}"/>`)
    .join("")}</svg>`;
  await page.setViewportSize({ width: 1200, height: 630 });
  await page.setContent(`<html><head><style>
    @font-face { font-family: Geist; src: url(data:font/woff2;base64,${geist}) format("woff2"); font-weight: 100 900; }
    body { margin: 0; width: 1200px; height: 630px; box-sizing: border-box; padding: 72px; display: flex; flex-direction: column; justify-content: space-between;
      font-family: Geist, sans-serif; background: ${COLORS.ivory}; color: ${COLORS.charcoal};
      background-image: linear-gradient(to right, rgba(32,35,31,.06) 1px, transparent 1px), linear-gradient(to bottom, rgba(32,35,31,.06) 1px, transparent 1px);
      background-size: 40px 40px; }
    h1 { margin: 0; font-size: 104px; font-weight: 650; letter-spacing: -4px; line-height: .95; }
    h1 span { color: ${COLORS.sage}; display: block; }
    p { margin: 0; font-size: 24px; color: #62685F; letter-spacing: 3px; text-transform: uppercase; }
  </style></head><body>${wm}<h1>Better websites.<span>Smarter businesses.</span></h1><p>Frame &amp; Flow Studio · Websites &amp; Business Automation</p></body></html>`);
  await page.evaluate("document.fonts.ready"); // runs in the browser page
  fs.writeFileSync(path.join(root, "public/og.png"), await page.screenshot({ clip: { x: 0, y: 0, width: 1200, height: 630 } }));
  await browser.close();
  console.log("Raster icons written.");
})();
